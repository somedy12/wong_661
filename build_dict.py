# -*- coding: utf-8 -*-
"""
Build a compact dictionary JSON for the 同键 (Tongjian) mixed CN/EN input method.

Inputs (in ./data):
  pinyin_simp.dict.yaml  RIME simplified pinyin dict:  hanzi\tpinyin\tweight
  rime_essay.txt         RIME word-frequency list:     word\tfreq   (used for char bigram)
  en_50k.txt             English word frequency:       word\tfreq

Output:
  data/dict.json         compact dictionaries + char bigram + totals
"""
import json, math, re, sys, os

DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data')

# ---- tunables ----
CN_MIN_WEIGHT = 3        # drop pinyin entries with weight below this (rare/obscure)
CN_TOP_PER_KEY = 8       # keep at most this many homophones per pinyin key
EN_TOP = 20000           # keep top-N English words
BIGRAM_WORD_MIN_FREQ = 30   # only count bigrams from words with freq >= this
BIGRAM_MAX_LEN = 6       # only words up to this many chars for bigram stats
BIGRAM_TOP_PER_PREV = 6  # top-N next-chars per previous char
BIGRAM_PREV_MIN_COUNT = 150  # only keep prev chars seen >= this often
UNI_MIN_COUNT = 3        # char unigram floor

CJK_RE = re.compile(r'^[\u4e00-\u9fff]+$')

def read_lines(name):
    p = os.path.join(DATA, name)
    with open(p, encoding='utf-8') as f:
        return f.read().splitlines()

# ---------------- Chinese pinyin dict ----------------
cn = {}          # compact_pinyin -> list of [hanzi, weight]
rime_hanzi = set()  # every word RIME already assigns a pinyin to (authoritative)
rime_chars = set()  # every single char RIME maps (== the simplified character set)
total_cn_weight = 0
n_raw = 0
header_done = False
for line in read_lines('pinyin_simp.dict.yaml'):
    if not header_done:
        if line.strip() == '...':
            header_done = True
        continue
    line = line.strip()
    if not line:
        continue
    parts = line.split('\t')
    if len(parts) < 3:
        continue
    hanzi = parts[0].strip()
    py = parts[1].strip()
    try:
        w = int(parts[2].strip())
    except ValueError:
        continue
    n_raw += 1
    rime_hanzi.add(hanzi)
    if len(hanzi) == 1:
        rime_chars.add(hanzi)
    # normalize syllables: lue->lve, nue->nve (match prototype convention)
    syls = py.lower().split(' ')
    syls = [('lve' if s == 'lue' else 'nve' if s == 'nue' else s) for s in syls if s]
    compact = ''.join(syls)
    if not compact or not hanzi:
        continue
    if w < CN_MIN_WEIGHT:
        continue
    cn.setdefault(compact, []).append([hanzi, w])
    total_cn_weight += w

# ---------------- traditional Chinese character set (opencc-js TSCharacters) ----------------
trad_chars = set()
try:
    with open(os.path.join(DATA, 'opencc_pkg', 'package', 'dist', 'esm-lib', 'dict', 'TSCharacters.js'),
              encoding='utf-8') as f:
        ts_text = f.read()
    m = re.search(r'"([^"]*)"', ts_text)
    if m:
        for pair in m.group(1).split('|'):
            if pair:
                trad_chars.add(pair[0])
except (FileNotFoundError, IndexError):
    pass

# ---------------- enrich with essay word-frequency (pinyin via pinyin-pro) ----------------
# rime_essay.txt has 442k Chinese words with frequency but no pinyin; cn_extra.json
# (generated by gen_pinyin.js using pinyin-pro) supplies the tone-less pinyin.
# Add common essay words that RIME does not already cover, keeping only simplified words.
CN_EXTRA_MIN_FREQ = 100
CN_EXTRA_MAX = 80000
n_extra_added = 0
try:
    with open(os.path.join(DATA, 'cn_extra.json'), encoding='utf-8') as f:
        cn_extra = json.load(f)
except (FileNotFoundError, json.JSONDecodeError):
    cn_extra = {}

extra_new = []
for py, words in cn_extra.items():
    for hanzi, freq in words:
        if hanzi in rime_hanzi:
            continue
        if freq < CN_EXTRA_MIN_FREQ:
            continue
        # essay.txt is mixed simplified/traditional; keep only all-simplified words
        if any(ch in trad_chars for ch in hanzi):
            continue
        extra_new.append((hanzi, py, freq))
extra_new.sort(key=lambda x: -x[2])
extra_new = extra_new[:CN_EXTRA_MAX]
for hanzi, py, freq in extra_new:
    cn.setdefault(py, []).append([hanzi, freq])
    total_cn_weight += freq
    n_extra_added += 1

cn_final = {}
for k, v in cn.items():
    v.sort(key=lambda x: -x[1])
    cn_final[k] = v[:CN_TOP_PER_KEY]

n_cn_entries = sum(len(v) for v in cn_final.values())
# characters that the IME can actually output (candidate vocabulary)
cn_vocab = set()
for v in cn_final.values():
    for hanzi, _w in v:
        cn_vocab.update(hanzi)

# ---------------- English frequency (clean vocab) ----------------
# en_50k has real counts but contains foreign-word noise (e.g. "wo", "xiang").
# Filter the vocabulary by a clean rank-ordered common-word list (google 20k),
# keeping real counts where available and synthesizing a frequency otherwise.
en_counts = {}
for line in read_lines('en_50k.txt'):
    parts = line.split(' ')
    if len(parts) < 2:
        continue
    w = parts[0].strip().lower()
    if not re.fullmatch(r'[a-z]+', w):
        continue
    try:
        f = int(parts[-1].strip())
    except ValueError:
        continue
    en_counts[w] = f

google_words = []
for line in read_lines('google-20k.txt'):
    w = line.strip().lower()
    if re.fullmatch(r'[a-z]+', w):
        google_words.append(w)

en_final = {}
for rank, w in enumerate(google_words, start=1):
    if w in en_counts:
        en_final[w] = en_counts[w]
    else:
        en_final[w] = 20001 - rank  # small synthetic frequency for the tail
en_items = sorted(en_final.items(), key=lambda x: -x[1])[:EN_TOP]
en_final = {w: f for w, f in en_items}
total_en_weight = sum(en_final.values())

# ---------------- char bigram + unigram from essay ----------------
bigram_count = {}   # prev -> {next: count}
uni_count = {}      # char -> count
for line in read_lines('rime_essay.txt'):
    line = line.strip()
    if not line:
        continue
    parts = line.split('\t')
    if len(parts) < 2:
        continue
    word = parts[0].strip()
    try:
        f = int(parts[1].strip())
    except ValueError:
        continue
    if f < BIGRAM_WORD_MIN_FREQ or len(word) > BIGRAM_MAX_LEN:
        continue
    if not CJK_RE.match(word):
        continue
    for ch in word:
        uni_count[ch] = uni_count.get(ch, 0) + f
    for i in range(len(word) - 1):
        a, b = word[i], word[i + 1]
        bigram_count.setdefault(a, {}).setdefault(b, 0)
        bigram_count[a][b] += f

uni_total = sum(uni_count.values())

# char unigram log-prob (x100) — only for candidate chars (used as bigram backoff)
uni_final = {}
for ch, c in uni_count.items():
    if ch in cn_vocab and c >= UNI_MIN_COUNT:
        uni_final[ch] = round(100.0 * math.log(c / uni_total), 2)

# bigram transition log-prob (interpolated with unigram backoff), x100
# restrict to candidate chars only (transitions the IME can actually produce)
bigram_final = {}
for prev, nxt in bigram_count.items():
    if prev not in cn_vocab:
        continue
    pc = uni_count.get(prev, 0)
    if pc < BIGRAM_PREV_MIN_COUNT:
        continue
    rows = []
    for nxtch, c in nxt.items():
        if nxtch not in cn_vocab:
            continue
        bigram_p = c / pc
        unigram_p = uni_count.get(nxtch, 0) / uni_total
        interp = 0.7 * bigram_p + 0.3 * unigram_p
        lp = 100.0 * math.log(interp)
        rows.append([nxtch, round(lp, 2)])
    rows.sort(key=lambda x: -x[1])
    bigram_final[prev] = rows[:BIGRAM_TOP_PER_PREV]

# ---------------- totals for normalization (JS converts counts to log-prob) ----------------
cn_total = round(100.0 * math.log(total_cn_weight), 2)
en_total = round(100.0 * math.log(total_en_weight), 2)

out = {
    'cn': cn_final,        # pinyin -> [[hanzi, weight], ...]  (sorted desc)
    'cn_total': cn_total,  # 100*ln(sum cn weights)
    'en': en_final,        # word -> freq
    'en_total': en_total,  # 100*ln(sum en weights)
    'bigram': bigram_final,# prev char -> [[next char, 100*ln(p)], ...]
    'uni': uni_final,      # char -> 100*ln(char prob)
}

out_path = os.path.join(DATA, 'dict.json')
with open(out_path, 'w', encoding='utf-8') as f:
    json.dump(out, f, ensure_ascii=False, separators=(',', ':'))

size = os.path.getsize(out_path)
def jsz(o):
    return len(json.dumps(o, ensure_ascii=False, separators=(',', ':')))
print(f'raw pinyin lines        : {n_raw}')
print(f'extra essay words added : {n_extra_added}')
print(f'cn keys                 : {len(cn_final)}')
print(f'cn entries              : {n_cn_entries}')
print(f'en words                : {len(en_final)}')
print(f'bigram prev chars       : {len(bigram_final)}')
print(f'unigram chars           : {len(uni_final)}')
print(f'--- component sizes ---')
print(f'cn      : {jsz(cn_final)/1024:.1f} KB')
print(f'en      : {jsz(en_final)/1024:.1f} KB')
print(f'bigram  : {jsz(bigram_final)/1024:.1f} KB')
print(f'uni     : {jsz(uni_final)/1024:.1f} KB')
print(f'--- total ---')
print(f'dict.json size          : {size} bytes ({size/1024:.1f} KB)')
