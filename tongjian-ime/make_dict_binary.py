# -*- coding: utf-8 -*-
"""
把 ../data/dict.json 转成两样东西：
  1) src/dict_data.h  —— 内嵌进 DLL 的 C++ 头文件（字节数组，供 DictEngine 加载）
  2) src/dict.bin     —— 同样内容的二进制文件（便于人工检查）

二进制布局（小端）：
  magic "TJIE" 4B | version u32(1)
  cn_count u32
  per CN key(sorted): key_len u8, key(ascii), n u16, per cand: hanzi_len u8, hanzi(utf8), weight u32
  cn_total f64
  en_count u32
  per EN word(sorted): word_len u8, word(ascii), freq u32
  en_total f64
"""
import json, os, struct

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, 'src')
os.makedirs(SRC, exist_ok=True)

with open(os.path.join(ROOT, '..', 'data', 'dict.json'), encoding='utf-8') as f:
    d = json.load(f)

cn, en = d['cn'], d['en']
cn_total, en_total = float(d['cn_total']), float(d['en_total'])

buf = bytearray()
buf += b'TJIE' + struct.pack('<I', 1)

buf += struct.pack('<I', len(cn))
for key in sorted(cn.keys()):
    kb = key.encode('ascii')
    cands = cn[key]
    buf += struct.pack('<B', len(kb)) + kb
    buf += struct.pack('<H', len(cands))
    for hanzi, weight in cands:
        hb = hanzi.encode('utf-8')
        buf += struct.pack('<B', len(hb)) + hb
        buf += struct.pack('<I', int(weight))
buf += struct.pack('<d', cn_total)

buf += struct.pack('<I', len(en))
for word in sorted(en.keys()):
    wb = word.encode('ascii')
    buf += struct.pack('<B', len(wb)) + wb
    buf += struct.pack('<I', int(en[word]))
buf += struct.pack('<d', en_total)

# ---- 写 dict.bin ----
bin_path = os.path.join(SRC, 'dict.bin')
with open(bin_path, 'wb') as f:
    f.write(buf)

# ---- 写 dict_data.h（每字节用 \xNN，两个十六进制位后紧跟 \x 或引号，规避 \x 贪心）----
lines = []
lines.append('#pragma once')
lines.append('// Auto-generated by make_dict_binary.py. DO NOT EDIT.')
lines.append('static const unsigned char kDictData[] =')
CHUNK = 128
for i in range(0, len(buf), CHUNK):
    chunk = buf[i:i + CHUNK]
    s = '"' + ''.join('\\x%02x' % b for b in chunk) + '"'
    lines.append(s)
lines.append(';')
lines.append('static const unsigned int kDictSize = sizeof(kDictData) - 1;')

hdr_path = os.path.join(SRC, 'dict_data.h')
with open(hdr_path, 'w', encoding='ascii') as f:
    f.write('\n'.join(lines) + '\n')

print(f'written {bin_path}: {len(buf)} bytes ({len(buf)/1024:.1f} KB)')
print(f'written {hdr_path}: {os.path.getsize(hdr_path)/1024:.1f} KB')
print(f'  cn keys={len(cn)}  en words={len(en)}  cn_total={cn_total:.1f}  en_total={en_total:.1f}')
